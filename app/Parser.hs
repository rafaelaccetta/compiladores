nomeFriendlyToken t     = "'" ++ t ++ "'"

-- Função de erro para tabela first-follow
erroTabela :: String -> String -> String
erroTabela naoTerminal token =
    let follow    = followSet naoTerminal
        possiveis = possiveisGerados naoTerminal
        tkFriendly = nomeFriendlyToken token
        ntFriendly = nomeFriendlyNT naoTerminal
        listaPossiveis = intercalate " ou " (map nomeFriendlyToken possiveis)
    in if token `elem` follow && not (null possiveis)
         then if length possiveis == 1
              then "Erro de sintaxe: esperava " ++ ntFriendly ++ " (" ++ listaPossiveis ++ ") antes de " ++ tkFriendly ++ "."
              else "Erro de sintaxe: esperava " ++ ntFriendly ++ " (" ++ listaPossiveis ++ ") antes de " ++ tkFriendly ++ "."
         else "Erro de sintaxe: " ++ tkFriendly ++ " não esperado aqui. Esperava " ++ ntFriendly ++ "."


scanAux :: RDFA -> String -> [(String, String)] -> String -> [Int] -> String -> String -> String -> Either String [(String, String)]
scanAux rdfa@(RDFA _ trans strt fnl) str acc word state lword ltoken rstr = 
    case str of
        [] -> case fnl state of
            Nothing -> 
                if lword == "" 
                then Left ("Couldn't match string: " ++ word)
                else scanAux rdfa rstr (acc ++ [(ltoken, lword)]) [] strt "" "" ""
            Just token -> Right (acc ++ (if word == "" then [] else [(token, word)]))
        a:as -> 
            if a `elem` delimiters 
            then case fnl state of
                Nothing -> 
                    if word /= "" 
                    then 
                        if lword == "" 
                        then Left ("Couldn't match string: " ++ word)
                        else scanAux rdfa rstr (acc ++ [(ltoken, lword)]) [] strt "" "" ""
                    else scanAux rdfa as acc (if a `elem` whitespace then [] else [a]) (trans strt a) 
                            (case fnl (trans strt a) of
                                Nothing -> ""
                                Just _ -> [a])
                            (case fnl (trans strt a) of
                                Nothing -> ""
                                Just t -> t) 
                            as
                Just token -> 
                    case dropWhile (`elem` whitespace) str of
                        [] -> Right (acc ++ (if word == "" then [] else [(token, word)]))
                        b:bs -> scanAux rdfa bs (acc ++ (if word == "" then [] else [(token, word)])) [b] (trans strt b)
                                    (case fnl (trans strt b) of
                                        Nothing -> ""
                                        Just _ -> [b])
                                    (case fnl (trans strt b) of
                                        Nothing -> ""
                                        Just t -> t) 
                                    bs
            else 
                scanAux rdfa as acc (word ++ [a]) (trans state a)
                    (case fnl (trans state a) of
                        Nothing -> lword
                        Just _ -> lword ++ [a])
                    (case fnl (trans state a) of
                        Nothing -> ltoken
                        Just t -> t) 
                    (case fnl (trans state a) of
                        Nothing -> rstr
                        Just _ -> as) 

scan :: RDFA -> String -> Either String [(String, String)]
scan rdfa@(RDFA _ _ strt _) str = 
    scanAux rdfa str [] "" strt "" "" ""

